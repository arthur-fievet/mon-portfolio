function applyLang(lang) {
  const t = T[lang];

  // data-i18n attribute updates
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // innerHTML updates
  Object.entries(SEL).forEach(([key, sel]) => {
    const el = document.querySelector(sel);
    if (el && t[key] !== undefined) el.innerHTML = t[key];
  });

  // Complex text node updates
  if (t["m2-j1t"]) {
    const el = document.querySelector("#cv-exp-j1 h5");
    if (el) {
      const sp = el.querySelector("span");
      el.childNodes[0].textContent = t["m2-j1t"] + " ";
      if (sp) sp.textContent = "| " + t["m2-j1c"];
    }
  }
  if (t["m2-j2t"]) {
    const el = document.querySelector("#cv-exp-j2 h5");
    if (el) {
      const sp = el.querySelector("span");
      el.childNodes[0].textContent = t["m2-j2t"] + " ";
      if (sp) sp.textContent = "| " + t["m2-j2c"];
    }
  }

  // Education h6
  const edus = document.querySelectorAll("#portfolioModal2 .col-md-8 .mb-3 h6");
  const eduKeys = ["m2-e1","m2-e2","m2-e3"];
  edus.forEach((el, i) => { if (t[eduKeys[i]]) el.textContent = t[eduKeys[i]]; });

  // Education dates
  const dates = document.querySelectorAll("#portfolioModal2 .col-md-8 .mb-3 .text-primary.fw-bold");
  if (dates[0] && t["m2-e1d"]) dates[0].textContent = t["m2-e1d"];
  if (dates[1] && t["m2-e2d"]) dates[1].textContent = t["m2-e2d"];
  if (dates[2] && t["m2-e3d"]) dates[2].textContent = t["m2-e3d"];

  // Mention badge
  const mention = document.querySelector("#portfolioModal2 .badge.bg-success");
  if (mention && t["m2-e2m"]) mention.textContent = t["m2-e2m"];

  // Soft skills badges
  const badges = document.querySelectorAll("#portfolioModal2 .badge.rounded-pill");
  const skillKeys = ["m2-sk1","m2-sk2","m2-sk3"];
  badges.forEach((b, i) => { if (t[skillKeys[i]]) b.textContent = t[skillKeys[i]]; });

  // m4-dev (has strong tag)
  const m4dev = document.querySelector("#portfolioModal4 .text-start > p:first-of-type");
  if (m4dev && t["m4-dev"]) m4dev.innerHTML = t["m4-dev"];

  // Portfolio card captions (inside grid)
  const caps = document.querySelectorAll(".portfolio-caption-heading");
  const capMap = [["pc1",0],["pc4",3]];
  capMap.forEach(([key, idx]) => {
    if (caps[idx] && t[key]) caps[idx].textContent = t[key];
  });

  // modalTexte2 skills list
  const mt2h5 = document.querySelector("#modalTexte2 h5");
  if (mt2h5 && t["mt2-skills"]) mt2h5.textContent = t["mt2-skills"];
  const mt2li = document.querySelectorAll("#modalTexte2 ul li");
  if (mt2li[0] && t["mt2-s1"]) mt2li[0].textContent = t["mt2-s1"];
  if (mt2li[1] && t["mt2-s2"]) mt2li[1].textContent = t["mt2-s2"];
  if (mt2li[2] && t["mt2-s3"]) mt2li[2].textContent = t["mt2-s3"];

  // modalTexte3
  const mt3h5 = document.querySelector("#modalTexte3 h5");
  if (mt3h5 && t["mt3-skills"]) mt3h5.textContent = t["mt3-skills"];
  const mt3li = document.querySelectorAll("#modalTexte3 ul li");
  if (mt3li[0] && t["mt3-s1"]) mt3li[0].textContent = t["mt3-s1"];
  if (mt3li[1] && t["mt3-s2"]) mt3li[1].textContent = t["mt3-s2"];
  if (mt3li[2] && t["mt3-s3"]) mt3li[2].textContent = t["mt3-s3"];



  // modalTexte1 lbl p and link
  const mt1p = document.querySelectorAll("#modalTexte1 p");
  if (mt1p[0] && t["mt1-lbl"]) mt1p[0].textContent = t["mt1-lbl"];



  // Modal 3 - section headings
  const m3h3s = document.querySelectorAll("#portfolioModal3 h3.text-uppercase");
  if (m3h3s[0] && t["admin-title"])   m3h3s[0].textContent = t["admin-title"];
  if (m3h3s[1] && t["connect-title"]) m3h3s[1].textContent = t["connect-title"];
  if (m3h3s[2] && t["prog-title"])    m3h3s[2].textContent = t["prog-title"];
  if (m3h3s[3] && t["secu-title"])    m3h3s[3].textContent = t["secu-title"];
  if (m3h3s[4] && t["surv-title"])    m3h3s[4].textContent = t["surv-title"];

  const m3h5s = document.querySelectorAll("#portfolioModal3 h5.fw-bold.text-primary");
  if (m3h5s[0] && t["admin-level-1"])   m3h5s[0].textContent = t["admin-level-1"];
  if (m3h5s[1] && t["admin-level-2"])   m3h5s[1].textContent = t["admin-level-2"];
  if (m3h5s[2] && t["connect-level-1"]) m3h5s[2].textContent = t["connect-level-1"];
  if (m3h5s[3] && t["connect-level-2"]) m3h5s[3].textContent = t["connect-level-2"];
  if (m3h5s[4] && t["prog-level-1"])    m3h5s[4].textContent = t["prog-level-1"];
  if (m3h5s[5] && t["prog-level-2"])    m3h5s[5].textContent = t["prog-level-2"];
  if (m3h5s[6] && t["secu-level-1"])    m3h5s[6].textContent = t["secu-level-1"];
  if (m3h5s[7] && t["surv-level-1"])    m3h5s[7].textContent = t["surv-level-1"];

  const noProj = document.querySelector("#portfolioModal3 .fst-italic");
  if (noProj && t["no-project"]) noProj.textContent = t["no-project"];

  // Modal 3 - AC descriptions
  const acGroups = [
    ["ac1101","ac1102","ac1103","ac1104","ac1105","ac1106"],
    ["ac2101","ac2102","ac2103","ac2104","ac2105","ac2106"],
    ["ac1201","ac1202","ac1203","ac1204","ac1205"],
    ["ac2201","ac2202","ac2203","ac2204","ac2205"],
    ["ac1301","ac1302","ac1303","ac1304","ac1305","ac1306"],
    ["ac2301","ac2302","ac2303","ac2304","ac2305"],
    ["ac2401cyber","ac2402cyber","ac2403cyber","ac2404cyber","ac2405cyber","ac2406cyber"],
    ["ac2501cyber","ac2502cyber"],
  ];
  document.querySelectorAll("#portfolioModal3 .ac-list").forEach((ul, si) => {
    ul.querySelectorAll("li").forEach((li, idx) => {
      const key = acGroups[si]?.[idx];
      if (key && t[key]) {
        const desc = li.querySelector(".ac-desc");
        if (desc) {
          desc.textContent = t[key];
        } else {
          const spans = li.querySelectorAll("span:not(.tiret):not(.badge-ac)");
          if (spans[0]) spans[0].textContent = t[key];
        }
      }
    });
  });

  // Modal 4 - list items (only the text node, after the strong label)
  const m4lis = document.querySelectorAll("#portfolioModal4 .list-group-item");
  const m4liKeys = [null,"m4-li2","m4-li3","m4-li4","m4-li5","m4-li6"];
  m4lis.forEach((li, i) => {
    const key = m4liKeys[i];
    if (key && t[key]) {
      // Replace last text node (after <strong>)
      const nodes = li.childNodes;
      for (let n = nodes.length - 1; n >= 0; n--) {
        if (nodes[n].nodeType === 3 && nodes[n].textContent.trim()) {
          nodes[n].textContent = " " + t[key];
          break;
        }
      }
    }
  });

  // Modal 4 - translate French-only strong labels by index
  const m4Strongs = document.querySelectorAll("#portfolioModal4 .list-group-item strong");
  const m4StrongFR = ["Ic\u00f4nes :", "Polices :", "Photo d\u2019accueil :"];
  const m4StrongEN = ["Icons:", "Fonts:", "Home photo:"];
  const swapFrom = lang === "en" ? m4StrongFR : m4StrongEN;
  const swapTo   = lang === "en" ? m4StrongEN : m4StrongFR;
  m4Strongs.forEach(el => {
    const idx = swapFrom.findIndex(s => el.textContent.trim().startsWith(s.replace(/\s/,"")));
    if (idx >= 0) el.textContent = swapTo[idx];
  });

  // Update button states
  document.getElementById("btn-fr").classList.toggle("lang-active", lang === "fr");
  document.getElementById("btn-en").classList.toggle("lang-active", lang === "en");
  document.documentElement.lang = lang;
  localStorage.setItem("lang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang(localStorage.getItem("lang") || "fr");
  document.getElementById("btn-fr").addEventListener("click", () => applyLang("fr"));
  document.getElementById("btn-en").addEventListener("click", () => applyLang("en"));
});
